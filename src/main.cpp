// minic - a small compiler for a tiny imperative language.
//
//   source -> tokens -> AST -> (sema) -> optimized AST -> bytecode -> VM
//
// Usage: minic <file.mc> [options]   (run `minic --help` for the options)

#include <cstdlib>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>

#include "ast.hpp"
#include "bytecode.hpp"
#include "codegen.hpp"
#include "lexer.hpp"
#include "optimizer.hpp"
#include "parser.hpp"
#include "sema.hpp"
#include "vm.hpp"

namespace {

void usage(std::ostream& os) {
    os << "usage: minic <file.mc> [options]\n"
          "  --dump-tokens   print the token stream\n"
          "  --dump-ast      print the AST after parsing\n"
          "  --dump-opt      print the AST after optimization\n"
          "  --disasm        print the generated bytecode\n"
          "  --no-opt        skip the optimizer\n"
          "  --no-run        compile only, do not execute\n"
          "  --stats         print optimizer and VM statistics to stderr\n"
          "  --max-steps N   abort after N VM instructions (default 100000000)\n"
          "  --help          show this message\n";
}

}  // namespace

int main(int argc, char** argv) {
    std::string path;
    bool dumpTokens = false, dumpAst = false, dumpOpt = false, disasm = false;
    bool optimize = true, run = true, stats = false;
    uint64_t maxSteps = 100000000ULL;

    for (int i = 1; i < argc; ++i) {
        std::string a = argv[i];
        if (a == "--dump-tokens") dumpTokens = true;
        else if (a == "--dump-ast") dumpAst = true;
        else if (a == "--dump-opt") dumpOpt = true;
        else if (a == "--disasm") disasm = true;
        else if (a == "--no-opt") optimize = false;
        else if (a == "--no-run") run = false;
        else if (a == "--stats") stats = true;
        else if (a == "--max-steps" && i + 1 < argc) {
            char* end = nullptr;
            maxSteps = std::strtoull(argv[++i], &end, 10);
            if (end == nullptr || *end != '\0') { usage(std::cerr); return 64; }
        } else if (a == "--help" || a == "-h") { usage(std::cout); return 0; }
        else if (!a.empty() && a[0] == '-') { std::cerr << "unknown option: " << a << "\n"; usage(std::cerr); return 64; }
        else if (path.empty()) path = a;
        else { usage(std::cerr); return 64; }
    }
    if (path.empty()) { usage(std::cerr); return 64; }

    std::ifstream in(path);
    if (!in) { std::cerr << "error: cannot open '" << path << "'\n"; return 64; }
    std::stringstream buf;
    buf << in.rdbuf();

    try {
        // Stage 1: lexing
        minic::Lexer lexer(buf.str());
        auto tokens = lexer.tokenize();
        if (dumpTokens)
            for (const auto& t : tokens)
                std::cout << t.line << ": " << minic::tokName(t.type) << "  '" << t.text << "'\n";

        // Stage 2: parsing
        minic::Parser parser(std::move(tokens));
        auto program = parser.parseProgram();
        if (dumpAst) std::cout << minic::dumpStmt(*program);

        // Stage 3: semantic checks + variable slots (before optimizing, see sema.hpp)
        minic::Sema sema;
        minic::SymbolTable symbols = sema.analyze(*program);

        // Stage 4: optimization
        minic::OptStats optStats;
        if (optimize) {
            minic::Optimizer opt(optStats);
            opt.run(*program);
            if (dumpOpt) std::cout << minic::dumpStmt(*program);
        }

        // Stage 5: code generation
        minic::CodeGen gen(symbols);
        minic::BytecodeProgram bytecode = gen.generate(*program);
        if (disasm) std::cout << minic::disassemble(bytecode);

        if (stats && optimize)
            std::cerr << "[opt] folded expressions: " << optStats.foldedExprs
                      << ", dead branches: " << optStats.deadBranches
                      << ", dead loops: " << optStats.deadLoops << "\n";
        if (stats) std::cerr << "[codegen] instructions: " << bytecode.code.size() << "\n";

        // Stage 6: execution
        if (run) {
            std::cout.flush();
            minic::VMStats vm = minic::runVM(bytecode, std::cout, maxSteps);
            if (stats) std::cerr << "[vm] steps executed: " << vm.steps << "\n";
        }
    } catch (const minic::CompileError& e) {
        std::cout.flush();
        std::cerr << "error: " << e.what() << "\n";
        return 1;
    } catch (const minic::RuntimeError& e) {
        std::cout.flush();
        std::cerr << "runtime error: " << e.what() << "\n";
        return 2;
    }
    return 0;
}
