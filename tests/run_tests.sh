#!/usr/bin/env bash
# Test runner for minic.  Usage: tests/run_tests.sh path/to/minic
#
# 1. programs/*.mc      output must equal programs/*.expected in four modes:
#                       bytecode VM and SSA IR interpreter, each with AND without
#                       the optimizers (optimizing must never change meaning).
# 2. errors/*.mc        must exit with the code in *.exit and print the text in
#                       *.stderr (substring match). Optional *.args holds flags.
#                       Runtime errors (exit 2) are also checked through the IR.
# 3. optimizer checks   assertions about the generated bytecode.
# 4. ir optimizer       assertions about the optimized SSA IR.
set -u

MINIC="${1:?usage: run_tests.sh path/to/minic}"
DIR="$(cd "$(dirname "$0")" && pwd)"
pass=0
fail=0

ok()  { pass=$((pass + 1)); printf '  PASS  %s\n' "$1"; }
bad() { fail=$((fail + 1)); printf '  FAIL  %s\n' "$1"; [ -n "${2:-}" ] && printf '        %s\n' "$2"; }

echo "== programs (bytecode and SSA IR, optimized and unoptimized) =="
for src in "$DIR"/programs/*.mc; do
    name="$(basename "$src" .mc)"
    expected="$DIR/programs/$name.expected"
    for mode in "" "--no-opt" "--ir" "--ir --no-opt"; do
        label="$name ${mode:-(opt)}"
        actual="$("$MINIC" "$src" $mode 2>&1)"
        if [ "$actual" == "$(cat "$expected")" ]; then ok "$label"
        else bad "$label" "got: $(printf '%s' "$actual" | head -c 200 | tr '\n' ' ')"; fi
    done
done

echo "== error handling =="
for src in "$DIR"/errors/*.mc; do
    name="$(basename "$src" .mc)"
    want_exit="$(cat "$DIR/errors/$name.exit")"
    want_msg="$(cat "$DIR/errors/$name.stderr")"
    args=""
    [ -f "$DIR/errors/$name.args" ] && args="$(cat "$DIR/errors/$name.args")"
    stderr="$("$MINIC" "$src" $args 2>&1 >/dev/null)"
    code=$?
    if [ "$code" == "$want_exit" ] && [[ "$stderr" == *"$want_msg"* ]]; then ok "$name"
    else bad "$name" "exit=$code (want $want_exit), stderr='$stderr'"; fi
    if [ "$want_exit" == "2" ]; then
        # The message names a bytecode offset or an IR function; compare up to the " (".
        stderr="$("$MINIC" "$src" $args --ir 2>&1 >/dev/null)"
        code=$?
        if [ "$code" == "2" ] && [[ "$stderr" == *"${want_msg%% (*}"* ]]; then ok "$name --ir"
        else bad "$name --ir" "exit=$code (want 2), stderr='$stderr'"; fi
    fi
done

echo "== optimizer =="
# Everything in constant_folding's first line should collapse to a single PUSH 10.
asm="$("$MINIC" "$DIR/programs/constant_folding.mc" --no-run --disasm)"
first_two="$(printf '%s\n' "$asm" | head -2 | awk '{print $2, $3}' | tr '\n' ' ')"
if [ "$first_two" == "PUSH 10 PRINT  " ] || [ "$first_two" == "PUSH 10 PRINT " ]; then ok "2*3+4 folds to PUSH 10"
else bad "2*3+4 folds to PUSH 10" "first instructions: $first_two"; fi

noopt_len="$("$MINIC" "$DIR/programs/constant_folding.mc" --no-run --disasm --no-opt | wc -l)"
opt_len="$("$MINIC" "$DIR/programs/constant_folding.mc" --no-run --disasm | wc -l)"
if [ "$opt_len" -lt "$noopt_len" ]; then ok "optimized bytecode is shorter ($opt_len < $noopt_len)"
else bad "optimized bytecode is shorter" "opt=$opt_len noopt=$noopt_len"; fi

stats="$("$MINIC" "$DIR/programs/dead_code.mc" --no-run --stats 2>&1)"
if [[ "$stats" == *"dead branches: 5"* && "$stats" == *"dead loops: 1"* ]]; then ok "dead_code stats (5 branches, 1 loop)"
else bad "dead_code stats" "$stats"; fi

stats="$("$MINIC" "$DIR/programs/returns.mc" --no-run --stats 2>&1)"
if [[ "$stats" == *"unreachable statements: 1"* ]]; then ok "code after return is removed (1 statement)"
else bad "code after return is removed" "$stats"; fi

# A call must survive optimization even when its result is multiplied by 0.
asm="$("$MINIC" "$DIR/programs/returns.mc" --no-run --disasm)"
if [[ "$asm" == *"; side_effect_kept"* ]]; then ok "calls are not folded away"
else bad "calls are not folded away"; fi

echo "== ir optimizer =="
ir="$("$MINIC" "$DIR/programs/ssa_passes.mc" --no-run --dump-ir)"
count() { printf '%s\n' "$ir" | grep -c -- "$1"; }
if [[ "$ir" == *"const 8"* ]] && [ "$(count ' br ')" == "0" ]; then ok "constants propagate through variables and decide the branch"
else bad "constants propagate through variables and decide the branch" "br count: $(count ' br ')"; fi
if [ "$(count ' mul ')" == "1" ] && [ "$(count ' add ')" == "1" ]; then ok "repeated x * x + 1 is computed once (1 mul, 1 add in the whole program)"
else bad "common subexpressions" "mul: $(count ' mul ')  add: $(count ' add ')"; fi
if [ "$(count ' sub ')" == "0" ]; then ok "x * y + 1 - (y * x + 1) folds to 0"
else bad "x * y + 1 - (y * x + 1) folds to 0" "sub count: $(count ' sub ')"; fi

ir="$("$MINIC" "$DIR/programs/sum_to_100.mc" --no-run --dump-ir)"
if [ "$(count ' phi ')" == "2" ]; then ok "the sum loop needs exactly 2 phis (i and sum)"
else bad "the sum loop needs exactly 2 phis" "phi count: $(count ' phi ')"; fi

# The call must survive even though its result is multiplied by 0.
ir="$("$MINIC" "$DIR/programs/returns.mc" --no-run --dump-ir)"
if [[ "$ir" == *"call side_effect_kept"* ]]; then ok "the IR optimizer keeps calls"
else bad "the IR optimizer keeps calls"; fi

stats="$("$MINIC" "$DIR/programs/ssa_passes.mc" --no-run --dump-ir --stats 2>&1 >/dev/null)"
before="$(printf '%s' "$stats" | sed -n 's/.*\[ir\] instructions: \([0-9]*\) -> .*/\1/p')"
after="$(printf '%s' "$stats" | sed -n 's/.*\[ir\] instructions: [0-9]* -> \([0-9]*\).*/\1/p')"
if [ -n "$before" ] && [ "$after" -lt "$before" ]; then ok "optimized IR is smaller ($after < $before instructions)"
else bad "optimized IR is smaller" "$stats"; fi

echo
echo "passed: $pass   failed: $fail"
[ "$fail" -eq 0 ]
